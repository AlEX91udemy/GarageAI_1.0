export function getWorkHint(title: string, category?: string): string {
  if (!title) return "Рекомендуется проверить состояние смежных узлов при проведении работ.";

  const lower = title.toLowerCase();

  if (lower.includes("подрамник") || lower.includes("сайлентблок")) {
    return "💡 Проверьте состояние болтов подрамника и опоры двигателя. После сборки обязательно выполните сход-развал.";
  }
  if (lower.includes("колодк") || lower.includes("тормоз")) {
    return "💡 Оцените остаточную толщину тормозных дисков (не менее допустимого минимума), смажьте направляющие термостойкой смазкой.";
  }
  if (lower.includes("антифриз") || lower.includes("охлаждающ")) {
    return "💡 Промойте систему дистиллятом до чистой воды. Проверьте крышку радиатора / расширительного бачка на сброс давления.";
  }
  if (lower.includes("вариатор") || lower.includes("cvt") || lower.includes("акпп")) {
    return "💡 Замените оба фильтра (грубой и тонкой очистки), очистите магниты поддона и сбросьте счетчик деградации жидкости.";
  }
  if (lower.includes("стойк") || lower.includes("стабилизатор")) {
    return "💡 Замену стоек стабилизатора лучше делать парами. Финальную затяжку гаек проводите под рабочей нагрузкой подвески.";
  }
  if (lower.includes("свеч")) {
    return "💡 Выкручивайте свечи только на холодном ДВС. Осмотрите резиновые наконечники катушек зажигания на отсутствие трещин и следов пробоя.";
  }
  if (lower.includes("дроссел")) {
    return "💡 Не давите на заслонку силой. Используйте специальный спрей-очиститель и выполните калибровку (обучение) холостого хода.";
  }
  if (lower.includes("масл") && (lower.includes("двигател") || lower.includes("двс") || lower.includes("мотор"))) {
    return "💡 Меняйте уплотнительное кольцо сливной пробки при каждой замене. Не перетягивайте масляный фильтр.";
  }
  if (lower.includes("развал") || lower.includes("сход")) {
    return "💡 Перед регулировкой убедитесь, что в сайлентблоках и шаровых опорах нет люфтов, а давление в шинах соответствует заводскому.";
  }
  if (lower.includes("ремен") || lower.includes("грм") || lower.includes("ролик")) {
    return "💡 Вместе с ремнем проверьте люфт подшипников роликов, помпы и обгонной муфты генератора.";
  }
  if (lower.includes("салон") || lower.includes("воздушн") || lower.includes("фильтр")) {
    return "💡 Пропылесосьте или протрите корпус фильтра от листьев и песка перед установкой нового фильтрующего элемента.";
  }
  if (lower.includes("редуктор") || lower.includes("раздатк")) {
    return "💡 Всегда сначала откручивайте заливную пробку перед сливной, чтобы не остаться с пустым узлом.";
  }

  if (category === "Подвеска и рулевое") {
    return "💡 Проведите комплексную диагностику рычагов и шаровых опор, при вмешательстве в геометрию сделайте сход-развал.";
  }
  if (category === "Тормозная система") {
    return "💡 Проверьте состояние тормозных шлангов и равномерность износа колодок с обеих сторон колесной оси.";
  }
  if (category === "ТО и замена жидкостей") {
    return "💡 Сверяйте допуски жидкостей с руководством по эксплуатации вашего автомобиля.";
  }

  return "💡 Рекомендуется выполнить в рамках ближайшего ТО и зафиксировать номер установленной детали в журнале.";
}
